#!/usr/bin/env python3
"""段 5 —— 要素が無限個なら。有限で正しいことが、極限で正しいとは限らない。

    python3 roadmap/stage5_infinite.py

Series III は「三つである必要は無い、任意の n ≥ 2 で成り立つ」を示した。
次の一歩は n → ∞ である。ところが**そこで一つ、性質が壊れる。**

    作用素ノルム ‖A‖   有限の切り出しから、極限へちゃんと収束する
    スペクトル半径 ρ   **収束しない。** どの n でも同じ誤った値を返しうる

そしてこれは、この一連の作業にとって具合の悪い結果である。ここまでは
「論文は ‖A‖₂ を使っているが、本当に効いているのは ρ だ」と言ってきた。
**無限次元では、その関係が逆になる。**ρ のほうが、有限の計算から取れなくなる。

見せ方はこうする。重み付きの片側ずらしを考える。

    (A x)ᵢ = aᵢ x_{i−1}          （i = 1, 2, 3, … 、x₀ の項は無い）

これを n×n で切ると、狭義下三角の行列になる。**冪零である。**だから
どの n でも ρ = 0。ところが ℓ² 上の本物の作用素のスペクトル半径は、
重みが一定 a なら a である。**0 と a は、n をいくら上げても近づかない。**

三篇の設定（巡回置換）は、輪を閉じている。閉じていれば切り出しても ρ = a で、
極限と一致する。**輪を閉じているかどうかで、有限の計算が意味を持つかどうかが
変わる。**Series III の「任意の n」は、その条件つきで読む必要がある。

NumPy のみ。乱数種は固定。
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

__all__ = ["weighted_shift", "transient_profile"]


def weighted_shift(n, a, cyclic):
    """(Ax)ᵢ = aᵢ x_{i−1} の n×n 切り出し。

    cyclic=True なら x₀ の代わりに x_{n−1} を使う（輪を閉じる）。三篇の設定。
    cyclic=False なら端で切る。無限次元の片側ずらしの、素直な切り出し。
    """
    a = np.full(n, float(a)) if np.ndim(a) == 0 else np.asarray(a, dtype=float)
    A = np.zeros((n, n))
    for i in range(n):
        j = i - 1
        if j < 0:
            if not cyclic:
                continue
            j = n - 1
        A[i, j] = a[i]
    return A


def transient_profile(A, steps):
    """‖Aᵏ‖₂ の列。どこで 0 になるか（有限で終わるか）を見るため。"""
    out, M = [], np.eye(A.shape[0])
    for _ in range(steps):
        M = A @ M
        out.append(float(np.linalg.norm(M, 2)))
    return np.array(out)


if __name__ == "__main__":
    np.set_printoptions(precision=6, suppress=True)

    def title(s):
        print("\n" + s)
        print("-" * 72)

    a = 0.9

    title("1. 切り出した ρ は、輪を閉じるかどうかで変わる")
    print("     n    輪を閉じる ρ    端で切る ρ    ‖A‖₂（両方とも）")
    for n in (2, 3, 5, 10, 50, 200):
        Ac = weighted_shift(n, a, cyclic=True)
        Ao = weighted_shift(n, a, cyclic=False)
        print("  %4d   %12.6f   %11.6f   %10.6f"
              % (n, np.max(np.abs(np.linalg.eigvals(Ac))),
                 np.max(np.abs(np.linalg.eigvals(Ao))),
                 np.linalg.norm(Ao, 2)))
    print("""
  端で切ると、どの n でも ρ = 0 である。行列が冪零になるからで、n を上げても
  変わらない。輪を閉じれば ρ = a = %.1f で、これは極限と一致する。
  作用素ノルムはどちらでも a に一致する。""" % a)

    title("2. 無限次元での本当の値")
    print("""  ℓ² 上の重み付き片側ずらし（重みが一定 a）について

      ‖A‖ = a          スペクトル半径 = a          スペクトルは半径 a の閉円板

  これは既知の事実である（重み付きシフトのスペクトルの標準的な計算）。
  切り出しが返す ρ = 0 とは合わない。**「n をいくら大きくしても近づかない」
  という形の食い違いで、精度の問題ではない。**

     量              切り出しの極限     本当の値      一致するか
     ‖A‖₂            %.6f          %.6f      する
     ρ（輪を閉じる） %.6f          %.6f      する
     ρ（端で切る）   %.6f          %.6f      **しない**"""
          % (a, a, a, a, 0.0, a))

    title("3. 食い違いは、途中の挙動にそのまま出る")
    print("     n     ‖Aᵏ‖₂ が 0 になる k     第 20 段の ‖Aᵏ‖₂")
    for n in (5, 10, 30, 100):
        A = weighted_shift(n, a, cyclic=False)
        prof = transient_profile(A, 40)
        zero_at = int(np.argmax(prof < 1e-14)) + 1 if (prof < 1e-14).any() else -1
        print("  %4d   %18s   %18.6g"
              % (n, str(zero_at) if zero_at > 0 else "40 段では 0 にならない",
                 prof[19]))
    print("""
  端で切った系は、第 n 段でぴたりと 0 になる。**有限で終わる。**
  n を上げるほど終わる時点が遠のき、極限では終わらない。
  「どの n でも有限で終わる」は正しいのに、「極限でも有限で終わる」は誤りである。
  Series III の「任意の n で成り立つ」から極限を言うと、ここを踏む。""")

    title("4. 輪を閉じた側では、素直に収束する")
    print("     n     ρ        ‖A‖₂      第 20 段の ‖Aᵏ‖₂     a²⁰ = %.6g" % a ** 20)
    for n in (3, 5, 10, 50, 200):
        A = weighted_shift(n, a, cyclic=True)
        prof = transient_profile(A, 20)
        print("  %4d   %.6f   %.6f   %16.6g" % (
            n, np.max(np.abs(np.linalg.eigvals(A))), np.linalg.norm(A, 2), prof[-1]))
    print("""
  こちらは n に依らない。置換が等長であること、輪が閉じていることの両方が
  効いている。**三篇が「任意の n」で通っているのは、この二つを仮定しているから
  である。**仮定を落とすと、n を上げる操作そのものが意味を変える。""")

    title("5. この段が、これまでの主張に対して持つ意味")
    print("""  ここまでこの一連の作業は、こう言ってきた。

      論文は ‖A‖₂ < 1 を使っているが、収束を決めているのは ρ(A) < 1 である。
      ρ のほうが鋭い。

  有限次元ではその通りである。**無限次元では、鋭さと計算しやすさが逆転する。**

      ‖A‖ は切り出しから極限へ渡る（下半連続で、うまく振る舞う）
      ρ は渡らない。切り出しの ρ の極限が、本物の ρ と一致する保証が無い

  つまり、無限次元へ持っていくなら、**論文が使っていた条件のほうが安全である。**
  ρ を使うには、切り出し以外の方法で押さえる必要がある。

  自分の側の主張を弱める結果だが、書かない理由が無い。""")

    print("\n" + "-" * 72)
    print("""独自性。重み付きシフトのスペクトルも、切り出しでスペクトルが渡らない
こと（スペクトル汚染）も、作用素論と数値解析の標準的な題材である。ここに新しい
数学は無い。**新しいのは、三篇の設定でそれを具体的に走らせ、「輪を閉じているか
どうか」が分かれ目だと示したこと、そして自分の側の主張の適用範囲を狭めたことだけ。**

合法性。実装は外部から持ち込んでいない。既知の事実を事実として述べているだけで、
特定の文献の記述を引き写してはいない。

限界。ここで「本当の値」と書いたものは、解析的に分かっている値であって、この
コードが計算したものではない。**無限次元の量を有限のコードで直接確かめることは
できない。**できないことを、できたふりで埋めない。""")
